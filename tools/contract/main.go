// Command contract generates extension constants and types from the Go protocol.
package main

import (
	"fmt"
	"github.com/Mahmoud-s-Khedr/idm-enhanced/internal/protocol"
	"os"
	"reflect"
	"strings"
)

func main() {
	s := fmt.Sprintf("// Code generated by go run ./tools/contract; DO NOT EDIT.\nexport const VERSION = %d;\nexport const MAX_MESSAGE = %d;\nexport const TIMEOUT_MS = %d;\nexport interface Message {\n", protocol.Version, protocol.MaxMessage, protocol.Timeout.Milliseconds())
	t := reflect.TypeFor[protocol.Message]()
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		tag := strings.Split(f.Tag.Get("json"), ",")
		optional := ""
		if len(tag) > 1 {
			optional = "?"
		}
		kind := "string"
		if f.Type.Kind() == reflect.Int {
			kind = "number"
		}
		s += fmt.Sprintf("  %s%s: %s;\n", tag[0], optional, kind)
	}
	s += "}\n"
	path := "extensions/shared/src/contract.ts"
	if len(os.Args) > 1 && os.Args[1] == "-check" {
		b, e := os.ReadFile(path)
		if e != nil || string(b) != s {
			fmt.Fprintln(os.Stderr, "protocol generation drift; run go run ./tools/contract")
			os.Exit(1)
		}
		return
	}
	if e := os.WriteFile(path, []byte(s), 0644); e != nil {
		fmt.Fprintln(os.Stderr, e)
		os.Exit(1)
	}
}
